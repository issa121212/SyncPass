-- Esquema inicial de SyncPass (fs2-api).
-- PostgreSQL 16. Las columnas Instant se mapean a timestamptz.

CREATE TABLE usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cognito_sub     VARCHAR(128) NOT NULL UNIQUE,
    email           VARCHAR(320) NOT NULL UNIQUE,
    nombre          VARCHAR(160) NOT NULL,
    creado_en       TIMESTAMPTZ NOT NULL,
    actualizado_en  TIMESTAMPTZ NOT NULL
);

CREATE TABLE usuario_roles (
    usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    rol        VARCHAR(40) NOT NULL,
    PRIMARY KEY (usuario_id, rol)
);

CREATE TABLE proyectos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(160) NOT NULL,
    descripcion     TEXT,
    area_tematica   VARCHAR(80),
    unidad_vecinal  VARCHAR(160),
    fecha_inicio    DATE,
    fecha_fin       DATE,
    estado          VARCHAR(20) NOT NULL,
    responsable_id  BIGINT NOT NULL REFERENCES usuarios (id),
    creado_en       TIMESTAMPTZ NOT NULL,
    actualizado_en  TIMESTAMPTZ NOT NULL
);

CREATE TABLE eventos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id     BIGINT NOT NULL REFERENCES proyectos (id) ON DELETE CASCADE,
    nombre          VARCHAR(160) NOT NULL,
    descripcion     TEXT,
    fecha_hora      TIMESTAMP NOT NULL,
    cupos           INTEGER NOT NULL,
    recinto         VARCHAR(160),
    direccion       VARCHAR(240),
    latitud         DOUBLE PRECISION,
    longitud        DOUBLE PRECISION,
    radio_metros    INTEGER,
    qr_contenido    VARCHAR(40) UNIQUE,
    estado          VARCHAR(20) NOT NULL,
    creado_en       TIMESTAMPTZ NOT NULL,
    actualizado_en  TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_eventos_proyecto ON eventos (proyecto_id);
CREATE INDEX idx_eventos_fecha ON eventos (fecha_hora);

CREATE TABLE inscripciones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id   BIGINT NOT NULL REFERENCES eventos (id) ON DELETE CASCADE,
    usuario_id  BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    estado      VARCHAR(20) NOT NULL,
    creado_en   TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_inscripcion_evento_usuario UNIQUE (evento_id, usuario_id)
);

CREATE INDEX idx_inscripciones_usuario ON inscripciones (usuario_id);

CREATE TABLE asistencias (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id           BIGINT NOT NULL REFERENCES eventos (id) ON DELETE CASCADE,
    usuario_id          BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    es_presente         BOOLEAN NOT NULL,
    marcado_en          TIMESTAMPTZ NOT NULL,
    latitud             DOUBLE PRECISION,
    longitud            DOUBLE PRECISION,
    precision_metros    DOUBLE PRECISION,
    origen              VARCHAR(20) NOT NULL,
    client_uuid         VARCHAR(64) UNIQUE,
    creado_en           TIMESTAMPTZ NOT NULL,
    actualizado_en      TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_asistencia_evento_usuario UNIQUE (evento_id, usuario_id)
);

CREATE INDEX idx_asistencias_usuario ON asistencias (usuario_id);
CREATE INDEX idx_asistencias_evento ON asistencias (evento_id);

CREATE TABLE encuestas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asistencia_id   BIGINT NOT NULL REFERENCES asistencias (id) ON DELETE CASCADE,
    satisfaccion    INTEGER NOT NULL,
    utilidad        INTEGER NOT NULL,
    comentarios     TEXT,
    enviado_en      TIMESTAMPTZ NOT NULL,
    creado_en       TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_encuesta_asistencia UNIQUE (asistencia_id),
    CONSTRAINT ck_encuesta_satisfaccion CHECK (satisfaccion BETWEEN 1 AND 5),
    CONSTRAINT ck_encuesta_utilidad CHECK (utilidad BETWEEN 1 AND 5)
);
